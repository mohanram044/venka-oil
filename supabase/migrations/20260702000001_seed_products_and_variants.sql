-- 3. Populate product_variants table explicitly from product variants JSON
INSERT INTO public.product_variants (product_id, size, price, stock, sku, is_active)
SELECT
  p.id,
  v->>'size',
  (v->>'price')::numeric,
  COALESCE((v->>'stock')::int, 0),
  COALESCE(p.sku || '-' || replace(v->>'size', ' ', ''), p.slug),
  true
FROM public.products p,
LATERAL jsonb_array_elements(p.variants) AS v
WHERE p.variants IS NOT NULL
ON CONFLICT (product_id, size) DO UPDATE SET
  price = EXCLUDED.price,
  sku = EXCLUDED.sku;
